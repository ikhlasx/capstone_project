"""Stage 1 discovery evidence: every figure in the discovery workbook is produced here,
so each claim can be traced to a reproducible count.

Usage: python discovery/analysis.py --data data --out discovery/evidence.md
"""
import argparse, json, re, statistics as st
from collections import Counter, defaultdict
from pathlib import Path


def pct(a, b):
    return f"{100 * a / b:.0f}%" if b else "n/a"


def mean(xs):
    xs = [x for x in xs if x is not None]
    return round(st.mean(xs), 2) if xs else None


def median(xs):
    xs = [x for x in xs if x is not None]
    return st.median(xs) if xs else None


def outcome_table(tickets, key, title):
    groups = defaultdict(list)
    for t in tickets:
        groups[key(t)].append(t)
    rows = [f"\n### {title}\n", "| Group | Tickets | CSAT | First-contact resolved | Escalated | Repeat contact | Median resolution (min) |",
            "|---|---|---|---|---|---|---|"]
    for g, ts in sorted(groups.items(), key=lambda kv: -len(kv[1])):
        h = [t["history"] for t in ts]
        n = len(ts)
        rows.append(f"| {g} | {n} | {mean([x['csat_rating'] for x in h])} | "
                    f"{pct(sum(bool(x['first_contact_resolution']) for x in h), n)} | "
                    f"{pct(sum(bool(x['escalated']) for x in h), n)} | "
                    f"{pct(sum(bool(x['repeat_contact']) for x in h), n)} | "
                    f"{median([x['resolution_time_minutes'] for x in h])} |")
    return "\n".join(rows)


PII = {
    "email address": re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+"),
    "phone number": re.compile(r"\+?\d[\d\s().-]{8,}\d"),
    "card-like number": re.compile(r"\b(?:\d[ -]?){13,16}\b"),
    "API key / token": re.compile(r"\b(?:sk|pk|key|tok|api)[-_][A-Za-z0-9_-]{8,}\b", re.I),
    "IP address": re.compile(r"\b\d{1,3}(?:\.\d{1,3}){3}\b"),
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="data")
    ap.add_argument("--out", default="discovery/evidence.md")
    a = ap.parse_args()
    d = Path(a.data)
    T = json.loads((d / "development_tickets.json").read_text())
    docs = json.loads((d / "documentation.json").read_text())
    n = len(T)
    L = lambda t: t["labels"]
    H = lambda t: t["history"]
    out = ["# Discovery evidence (generated by discovery/analysis.py)\n",
           f"Source: `development_tickets.json` ({n} tickets), `documentation.json` ({len(docs)} articles).",
           "History fields = what humans achieved today (the baseline).\n"]

    # ---- Section 2: counts
    out.append("## E1. Headline counts\n")
    out.append("| Measure | Figure |\n|---|---|")
    out.append(f"| Tickets | {n} |")
    out.append(f"| Channel split | {dict(Counter(t['channel'] for t in T).most_common())} |")
    out.append(f"| Urgency split | {dict(Counter(L(t)['urgency'] for t in T).most_common())} |")
    out.append(f"| Tier split | {dict(Counter(t['customer_tier'] for t in T).most_common())} |")
    out.append(f"| Non-fluent | {pct(sum(t['language_fluency']=='non_fluent' for t in T), n)} |")
    fcr = sum(bool(H(t)['first_contact_resolution']) for t in T)
    esc = sum(bool(H(t)['escalated']) for t in T)
    out.append(f"| First-contact resolution (history) | {pct(fcr, n)} |")
    out.append(f"| Escalated (history) | {pct(esc, n)} |")
    out.append(f"| Mean CSAT (history) | {mean([H(t)['csat_rating'] for t in T])} |")
    out.append(f"| Repeat contacts (history) | {pct(sum(bool(H(t)['repeat_contact']) for t in T), n)} |")
    ans = [t for t in T if L(t)["answerable_from_docs"]]
    out.append(f"| Answerable from existing docs | {len(ans)} ({pct(len(ans), n)}) |")
    ans_esc = [t for t in ans if H(t)["escalated"]]
    out.append(f"| Answerable but escalated by humans | {len(ans_esc)} ({pct(len(ans_esc), len(ans))} of answerable; "
               f"{pct(len(ans_esc), esc)} of all escalations) |")
    out.append(f"| Expected route (label) | {dict(Counter(L(t)['expected_route'] for t in T))} |")
    out.append(f"| must_not_auto_respond | {sum(bool(L(t)['must_not_auto_respond']) for t in T)} |")

    out.append(outcome_table(T, lambda t: "answerable" if L(t)["answerable_from_docs"] else "not answerable",
                             "E2. Outcomes: answerable vs not answerable from docs"))
    out.append(outcome_table(T, lambda t: t["channel"], "E3. Outcomes by channel"))
    out.append(outcome_table(T, lambda t: t["customer_tier"], "E4. Outcomes by tier"))
    out.append(outcome_table(T, lambda t: t["language_fluency"], "E5. Outcomes by language fluency"))
    out.append(outcome_table(T, lambda t: t["customer_region"], "E6. Outcomes by region"))
    out.append(outcome_table(T, lambda t: L(t)["urgency"], "E7. Outcomes by urgency"))

    # ---- Section 3: effort
    out.append("\n## E8. Volume vs effort by intent\n")
    out.append("Effort proxy = sum of historical resolution minutes (an estimate; elapsed time, not hands-on time).\n")
    out.append("| Intent | Volume share | Effort share | Answerable | Escalated | must_not_auto |\n|---|---|---|---|---|---|")
    mins = lambda t: H(t)["resolution_time_minutes"] or 0
    total = sum(mins(t) for t in T)
    by = defaultdict(list)
    for t in T:
        by[L(t)["intent"]].append(t)
    for intent, ts in sorted(by.items(), key=lambda kv: -sum(mins(t) for t in kv[1])):
        k = len(ts)
        out.append(f"| {intent} | {pct(k, n)} | {pct(sum(mins(t) for t in ts), total)} | "
                   f"{pct(sum(L(t)['answerable_from_docs'] for t in ts), k)} | "
                   f"{pct(sum(bool(H(t)['escalated']) for t in ts), k)} | "
                   f"{sum(bool(L(t)['must_not_auto_respond']) for t in ts)} |")

    # ---- Docs
    out.append("\n## E9. Documentation corpus\n")
    cited = Counter(i for t in T for i in L(t)["expected_doc_ids"])
    out.append("| Doc | Category | Last reviewed (days) | Tickets it answers |\n|---|---|---|---|")
    for doc in sorted(docs, key=lambda x: -cited[x["doc_id"]]):
        out.append(f"| {doc['doc_id']} | {doc.get('category')} | {doc.get('last_reviewed_days_ago')} | {cited[doc['doc_id']]} |")
    no_doc = [i for i, ts in by.items() if not any(L(t)["expected_doc_ids"] for t in ts)]
    out.append(f"\nIntents with no supporting article: {no_doc}")

    # ---- E11. Answerable tickets split by what humans actually did
    out.append("\n## E11. Answerable tickets: first-contact resolved vs escalated\n")
    out.append("Of the 357 tickets answerable from documentation, split by whether a human resolved at first contact or escalated.\n")
    ans_fcr = [t for t in ans if H(t)["first_contact_resolution"] and not H(t)["escalated"]]
    ans_esc2 = [t for t in ans if H(t)["escalated"]]
    out.append("| Group | Tickets | Median resolution (min) | Mean CSAT | Repeat contact |")
    out.append("|---|---|---|---|---|")
    out.append(
        f"| Answerable — resolved at first contact | {len(ans_fcr)} | "
        f"{median([H(t)['resolution_time_minutes'] for t in ans_fcr])} | "
        f"{mean([H(t)['csat_rating'] for t in ans_fcr])} | "
        f"{pct(sum(bool(H(t)['repeat_contact']) for t in ans_fcr), len(ans_fcr))} |"
    )
    out.append(
        f"| Answerable — escalated to tier two | {len(ans_esc2)} | "
        f"{median([H(t)['resolution_time_minutes'] for t in ans_esc2])} | "
        f"{mean([H(t)['csat_rating'] for t in ans_esc2])} | "
        f"{pct(sum(bool(H(t)['repeat_contact']) for t in ans_esc2), len(ans_esc2))} |"
    )
    out.append(f"\nSource: `history.first_contact_resolution`, `history.escalated`, `history.resolution_time_minutes`, `history.csat_rating`, `history.repeat_contact`.")

    # ---- Private data
    out.append("\n## E10. Private data appearing in ticket bodies\n")
    out.append("| Pattern | Tickets containing it |\n|---|---|")
    for name, rx in PII.items():
        out.append(f"| {name} | {sum(bool(rx.search(t['body'] or '')) for t in T)} |")

    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
